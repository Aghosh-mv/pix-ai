const { execSync } = require('child_process');
const fs = require('fs');
const path = require('path');

class GitAutopilot {
  constructor() {
    this.isRepo = this.checkRepo();
  }

  checkRepo() {
    try { execSync('git rev-parse --git-dir', { encoding: 'utf8', stdio: 'pipe' }); return true; } catch (e) { return false; }
  }

  run(cmd) {
    try { return execSync(cmd, { encoding: 'utf8', cwd: process.cwd() }).trim(); } catch (e) { return ''; }
  }

  // ── Auto-detect what changed and generate commit message ──
  autoCommit() {
    if (!this.isRepo) return { ok: false, error: 'not a git repo' };

    const status = this.run('git status --porcelain');
    if (!status) return { ok: false, error: 'nothing to commit' };

    const files = status.split('\n').filter(Boolean);
    const added = files.filter(f => f.startsWith('A') || f.includes('??')).map(f => f.slice(3));
    const modified = files.filter(f => f.startsWith('M') || f.includes(' M')).map(f => f.slice(3));
    const deleted = files.filter(f => f.startsWith('D') || f.includes(' D')).map(f => f.slice(3));

    // Generate smart commit message
    let msg = '';
    if (added.length > 0 && modified.length === 0 && deleted.length === 0) {
      msg = `feat: add ${added.length} file${added.length > 1 ? 's' : ''}`;
      if (added.length <= 3) msg += ` (${added.join(', ')})`;
    } else if (modified.length > 0 && added.length === 0 && deleted.length === 0) {
      msg = `update: modify ${modified.length} file${modified.length > 1 ? 's' : ''}`;
      if (modified.length <= 3) msg += ` (${modified.join(', ')})`;
    } else if (deleted.length > 0) {
      msg = `chore: remove ${deleted.length} file${deleted.length > 1 ? 's' : ''}`;
    } else {
      msg = `chore: update ${files.length} files`;
    }

    // Detect feature type from file extensions
    const exts = [...new Set(files.map(f => path.extname(f.slice(3)).toLowerCase()))];
    if (exts.includes('.js') || exts.includes('.ts')) msg = msg.replace('chore:', 'feat:');
    if (exts.includes('.md')) msg = msg.replace('feat:', 'docs:');
    if (exts.includes('.test.js') || exts.includes('.spec.js')) msg = `test: add tests`;
    if (exts.includes('.css') || exts.includes('.scss')) msg = msg.replace('chore:', 'style:');

    return this.commit(msg);
  }

  // ── Commit with message ──
  commit(msg) {
    if (!this.isRepo) return { ok: false, error: 'not a git repo' };
    this.run('git add -A');
    const result = this.run(`git commit -m "${msg}"`);
    if (result.includes('nothing to commit')) return { ok: false, error: 'nothing to commit' };
    return { ok: true, message: msg, hash: this.run('git rev-parse --short HEAD') };
  }

  // ── Auto-create PR ──
  autoPR(title, body) {
    if (!this.isRepo) return { ok: false, error: 'not a git repo' };

    const branch = this.run('git branch --show-current');
    const remote = this.run('git remote get-url origin');
    if (!remote) return { ok: false, error: 'no remote configured' };

    // Push branch
    this.run(`git push -u origin ${branch}`);

    // Create PR using gh CLI
    const prBody = body || `Auto-generated by Pix AI\n\nChanges:\n${this.run('git diff --stat HEAD~1')}`;
    const result = this.run(`gh pr create --title "${title || branch}" --body "${prBody}"`);

    if (result.includes('github.com')) {
      return { ok: true, url: result.match(/https:\/\/[^\s]+/)?.[0] };
    }
    return { ok: false, error: result || 'failed to create PR' };
  }

  // ── Smart rebase ──
  smartRebase() {
    if (!this.isRepo) return { ok: false, error: 'not a git repo' };

    const status = this.run('git status');
    if (!status.includes('behind')) return { ok: true, message: 'already up to date' };

    // Stash if needed
    const hasChanges = !status.includes('nothing to commit');
    if (hasChanges) this.run('git stash');

    // Rebase
    const result = this.run('git pull --rebase origin ' + this.run('git branch --show-current'));

    // Restore stash
    if (hasChanges) this.run('git stash pop');

    return { ok: !result.includes('CONFLICT'), message: result || 'rebased successfully' };
  }

  // ── Auto-stage specific files ──
  autoStage(patterns) {
    if (!this.isRepo) return { ok: false, error: 'not a git repo' };
    patterns.forEach(p => this.run(`git add ${p}`));
    return { ok: true, staged: patterns };
  }

  // ── Get git context for AI ──
  getContext() {
    if (!this.isRepo) return 'Not a git repository.';

    const branch = this.run('git branch --show-current');
    const status = this.run('git status --porcelain');
    const diff = this.run('git diff --stat');
    const log = this.run('git log --oneline -5');
    const remote = this.run('git remote get-url origin');

    let ctx = `Git:\n  branch: ${branch || 'detached'}\n  remote: ${remote || 'none'}\n  changes: ${status ? status.split('\n').length : 0} files\n`;
    if (diff) ctx += `  diff: ${diff}\n`;
    if (log) ctx += `  recent:\n${log.split('\n').map(l => '    ' + l).join('\n')}\n`;
    return ctx;
  }

  // ── Detect if work was done (for autopilot) ──
  hasUncommittedWork() {
    if (!this.isRepo) return false;
    return !!this.run('git status --porcelain');
  }

  // ── Auto-detect what needs doing ──
  getPendingActions() {
    const actions = [];
    if (this.hasUncommittedWork()) actions.push('commit');
    const status = this.run('git status');
    if (status.includes('behind')) actions.push('pull');
    if (status.includes('ahead')) actions.push('push');
    if (this.run('git branch --show-current') !== 'main' && this.hasUncommittedWork()) actions.push('pr');
    return actions;
  }
}

module.exports = GitAutopilot;
